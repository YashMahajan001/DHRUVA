"""Aero Turbofan Gas Turbine Physics Simulation Model.

Implements dual-spool (N1/N2) Brayton cycle dynamics, high bypass ratio aerodynamics,
FADEC fuel scheduling, turbine exhaust gas temperature (EGT) thermal response,
gross/net thrust calculation, and lubrication oil/vibration physics.
"""

from __future__ import annotations

import math
from typing import Optional, Dict, Any
from aero_engine.catalog.models import AeroEngineCatalogEntry


class AeroTurbofanModel:
    """Physics-based simulation core for commercial and defense turbofan engines."""

    def __init__(self, engine: AeroEngineCatalogEntry) -> None:
        self.engine = engine
        self.specs = engine.specifications
        self.limits = engine.operating_limits

        # Spool states
        self.n1_pct = 22.0  # Ground idle N1 %
        self.n2_pct = 62.0  # Ground idle N2 %
        self.egt_c = 440.0   # Idle EGT
        self.oil_temp_c = 70.0
        self.oil_press_psi = 48.0
        self.vibration_mils = 0.22
        self.time_s = 0.0

    def reset(self, initial_n1: Optional[float] = None) -> None:
        """Reset engine state to idle or specified spool speed."""
        self.n1_pct = initial_n1 if initial_n1 is not None else 22.0
        self.n2_pct = 60.0 + (self.n1_pct / 100.0) * 35.0
        self.egt_c = 440.0
        self.oil_temp_c = 70.0
        self.oil_press_psi = 48.0
        self.vibration_mils = 0.22
        self.time_s = 0.0

    def step(
        self,
        throttle: float,
        ambient_temp_c: float = 15.0,
        altitude_m: float = 0.0,
        mach: float = 0.0,
        dt_s: float = 0.05,
        faults: Optional[Dict[str, float]] = None,
    ) -> Dict[str, Any]:
        """Integrate dual-spool state over time step dt_s."""
        self.time_s += dt_s
        faults = faults or {}

        # 1. Atmospheric ambient conditions (ISA)
        t_isa_k = 288.15 - 0.0065 * min(11000.0, altitude_m)
        t_amb_k = ambient_temp_c + 273.15
        p_ratio = math.pow(max(0.01, 1.0 - 2.25577e-5 * altitude_m), 5.25588)
        theta = t_amb_k / 288.15
        delta = p_ratio

        # 2. FADEC Spool Speed Scheduling
        # Ground idle ~21-23% N1, 62% N2. Takeoff rating ~100-103% N1, 102% N2
        max_n1 = float(self.limits.max_n1_pct or 104.0)
        target_n1 = 22.0 + throttle * (max_n1 - 22.0)
        target_n2 = 62.0 + throttle * 40.0

        # Physical spool inertia: N2 spool accelerates faster than heavy fan N1
        tau_n2 = 0.95  # Fast HP core acceleration
        tau_n1 = 1.35  # Fan inertia response

        # Fault: Compressor stall / surge creates N2 oscillations
        n2_disturbance = 0.0
        if "FAULT_COMPRESSOR_STALL" in faults:
            stall_sev = faults["FAULT_COMPRESSOR_STALL"]
            n2_disturbance = math.sin(self.time_s * 18.0) * (4.5 * stall_sev)
            target_n1 *= (1.0 - 0.15 * stall_sev)

        self.n2_pct += (target_n2 + n2_disturbance - self.n2_pct) * (1.0 - math.exp(-dt_s / tau_n2))
        self.n1_pct += (target_n1 - self.n1_pct) * (1.0 - math.exp(-dt_s / tau_n1))

        # 3. Fuel Mass Flow (kg/h)
        # Governed by N2 core speed and burner pressure
        max_thrust_kn = float(self.specs.rated_takeoff_thrust_kn or 120.0)
        # Scaled specific fuel consumption
        base_ff = 400.0 + math.pow(self.n2_pct / 100.0, 3.2) * (max_thrust_kn * 22.5) * delta
        fuel_flow_kgh = base_ff * math.sqrt(theta)

        # Faults affecting fuel flow
        if "FAULT_TURBINE_CREEP" in faults:
            fuel_flow_kgh *= (1.0 + 0.08 * faults["FAULT_TURBINE_CREEP"])
        if "FAULT_NOZZLE_CLOG" in faults:
            fuel_flow_kgh *= (1.0 + 0.05 * faults["FAULT_NOZZLE_CLOG"])

        # 4. Exhaust Gas Temperature (EGT)
        # EGT increases with throttle, peaks during acceleration, increases with altitude lapse
        redline_egt = float(self.limits.max_turbine_egt_c or 950.0)
        idle_egt = 420.0
        accel_spike = max(0.0, (target_n2 - self.n2_pct)) * 1.8
        target_egt = idle_egt + (self.n2_pct - 62.0) * 11.5 + accel_spike

        # Faults affecting EGT
        if "FAULT_TURBINE_CREEP" in faults:
            target_egt += faults["FAULT_TURBINE_CREEP"] * 75.0  # Creep erodes clearance/efficiency
        if "FAULT_COMPRESSOR_STALL" in faults:
            target_egt += faults["FAULT_COMPRESSOR_STALL"] * 160.0  # Loss of airflow -> EGT spike
        if "FAULT_NOZZLE_CLOG" in faults:
            target_egt += faults["FAULT_NOZZLE_CLOG"] * 55.0
        if "FAULT_SENSOR_DRIFT" in faults:
            target_egt += faults["FAULT_SENSOR_DRIFT"] * 60.0

        tau_egt = 1.1
        self.egt_c += (target_egt - self.egt_c) * (1.0 - math.exp(-dt_s / tau_egt))

        # 5. Thrust Calculation
        # Thrust is primarily generated by bypass fan stream (75-85%) and core stream (15-25%)
        bpr = float(self.specs.bypass_ratio or 5.0)
        fan_thrust_ratio = math.pow(max(0.0, self.n1_pct / 100.0), 3.5)
        core_thrust_ratio = math.pow(max(0.0, (self.n2_pct - 50.0) / 50.0), 2.8)
        
        gross_thrust_kn = max_thrust_kn * (0.80 * fan_thrust_ratio + 0.20 * core_thrust_ratio) * delta

        # Ram drag deduction at forward speed: D_ram = m_dot * V_0
        ram_drag_factor = 1.0 - 0.22 * mach
        net_thrust_kn = max(0.0, gross_thrust_kn * ram_drag_factor)
        if "FAULT_COMPRESSOR_STALL" in faults:
            net_thrust_kn *= max(0.2, 1.0 - faults["FAULT_COMPRESSOR_STALL"] * 0.6)
        if "FAULT_TURBINE_CREEP" in faults:
            net_thrust_kn *= (1.0 - 0.05 * faults["FAULT_TURBINE_CREEP"])

        thrust_lbf = net_thrust_kn * 224.809

        # 6. Lubrication & Dynamics
        target_oil_press = 35.0 + (self.n2_pct / 100.0) * 35.0
        if "FAULT_OIL_LOSS" in faults:
            target_oil_press *= max(0.05, 1.0 - faults["FAULT_OIL_LOSS"] * 0.88)
        self.oil_press_psi += (target_oil_press - self.oil_press_psi) * (1.0 - math.exp(-dt_s / 0.5))

        target_oil_temp = ambient_temp_c + 55.0 + (self.n2_pct / 100.0) * 45.0
        if "FAULT_OIL_LOSS" in faults:
            target_oil_temp += faults["FAULT_OIL_LOSS"] * 50.0
        self.oil_temp_c += (target_oil_temp - self.oil_temp_c) * (1.0 - math.exp(-dt_s / 10.0))

        # Vibration: rotor imbalance
        base_vib = 0.15 + 0.25 * math.pow(self.n1_pct / 100.0, 2)
        if "FAULT_COMPRESSOR_STALL" in faults:
            base_vib += faults["FAULT_COMPRESSOR_STALL"] * 1.8
        self.vibration_mils = round(base_vib, 2)

        # Engine Pressure Ratio (EPR)
        epr = 1.0 + 0.65 * math.pow(self.n1_pct / 100.0, 2.5)

        return {
            "n1_pct": round(self.n1_pct, 1),
            "n2_pct": round(self.n2_pct, 1),
            "egt_c": round(self.egt_c, 1),
            "thrust_kn": round(net_thrust_kn, 1),
            "thrust_lbf": round(thrust_lbf, 0),
            "fuel_flow_kgh": round(fuel_flow_kgh, 1),
            "oil_press_psi": round(self.oil_press_psi, 1),
            "oil_temp_c": round(self.oil_temp_c, 1),
            "vibration_mils": round(self.vibration_mils, 2),
            "epr": round(epr, 2),
            "bypass_ratio": round(bpr, 1),
        }
