"""Aero Piston Engine Physics Simulation Model.

Implements Otto cycle dynamics, altitude lapse, manifold absolute pressure (MAP),
propeller load absorption, cylinder head temperature (CHT) thermal transient equations,
exhaust gas temperature (EGT), and oil system lubrication pressure.
"""

from __future__ import annotations

import math
from typing import Optional, Dict, Any
from aero_engine.catalog.models import AeroEngineCatalogEntry


class AeroPistonModel:
    """Physics-based simulation core for aircraft piston engines."""

    def __init__(self, engine: AeroEngineCatalogEntry) -> None:
        self.engine = engine
        self.specs = engine.specifications
        self.limits = engine.operating_limits

        # Engine state variables
        self.rpm = float(self.limits.idle_rpm or 700.0)
        self.map_inhg = 12.0
        self.cht_c = 85.0
        self.egt_c = 420.0
        self.oil_temp_c = 65.0
        self.oil_press_psi = 45.0
        self.fuel_press_psi = 24.0
        self.time_s = 0.0

    def reset(self, initial_rpm: Optional[float] = None) -> None:
        """Reset state to baseline idle or custom RPM."""
        self.rpm = initial_rpm if initial_rpm is not None else float(self.limits.idle_rpm or 700.0)
        self.map_inhg = 12.0
        self.cht_c = 85.0
        self.egt_c = 420.0
        self.oil_temp_c = 65.0
        self.oil_press_psi = 45.0
        self.time_s = 0.0

    def step(
        self,
        throttle: float,
        mixture: float = 1.0,  # 1.0 = rich for takeoff, 0.85 = best power, 0.75 = lean of peak
        ambient_temp_c: float = 15.0,
        altitude_m: float = 0.0,
        airspeed_kts: float = 100.0,
        dt_s: float = 0.05,
        faults: Optional[Dict[str, float]] = None,
    ) -> Dict[str, Any]:
        """Integrate one time step dt_s with aerodynamic and thermodynamic relations."""
        self.time_s += dt_s
        faults = faults or {}

        # 1. Standard Atmosphere pressure lapse
        # P_amb in inHg (Standard sea level = 29.92 inHg)
        p_ratio = math.pow(max(0.01, 1.0 - 2.25577e-5 * altitude_m), 5.25588)
        p_amb_inhg = 29.92 * p_ratio
        t_amb_k = (ambient_temp_c + 273.15)
        # Relative density sigma
        sigma = p_ratio * (288.15 / max(150.0, t_amb_k))

        # 2. Manifold Pressure (MAP)
        is_turbo = "TURBO" in self.engine.architecture.value
        if is_turbo:
            # Turbocharger wastegate maintains up to 40-45 inHg boost
            max_boost = float(self.limits.max_map_inhg or 42.0)
            target_map = 12.0 + throttle * (max_boost - 12.0)
        else:
            # Naturally aspirated: cannot exceed ambient pressure
            target_map = 11.5 + throttle * (p_amb_inhg - 11.5)

        # First-order throttle delay
        tau_map = 0.15
        self.map_inhg += (target_map - self.map_inhg) * (1.0 - math.exp(-dt_s / tau_map))

        # 3. Target RPM & Power
        rated_bhp = float(self.specs.rated_takeoff_power_bhp or 200.0)
        max_rpm = float(self.limits.max_rpm or 2700.0)
        idle_rpm = float(self.limits.idle_rpm or 650.0)

        # In an aircraft propeller system, RPM stabilizes where engine torque = prop absorption torque
        # Power proportional to (MAP / 29.92) * (RPM / max_rpm) * sigma
        power_fraction = max(0.05, (self.map_inhg / 29.92) * (self.rpm / max_rpm) * math.sqrt(sigma))
        power_bhp = rated_bhp * power_fraction * min(1.0, mixture / 0.85)

        # Fault: Detonation or cylinder fouling
        if "FAULT_CYLINDER_FOULING" in faults:
            power_bhp *= (1.0 - 0.25 * faults["FAULT_CYLINDER_FOULING"])

        # Target RPM from propeller governor / load
        target_rpm = idle_rpm + throttle * (max_rpm - idle_rpm) * math.sqrt(sigma)
        tau_rpm = 0.35
        self.rpm += (target_rpm - self.rpm) * (1.0 - math.exp(-dt_s / tau_rpm))
        self.rpm = max(idle_rpm * 0.8, min(max_rpm * 1.08, self.rpm))

        # 4. Fuel Flow (BSFC typical ~0.45 lb/(hp*h), 100LL is ~6.0 lb/US gallon)
        bsfc = 0.44 + 0.08 * (1.0 - mixture)
        fuel_flow_pph = power_bhp * bsfc
        fuel_flow_gph = fuel_flow_pph / 6.01

        # 5. CHT and EGT Thermal Dynamics
        # EGT responds rapidly (tau ~ 1.5s), peaks near stoichiometric mixture
        target_egt = 650.0 + (power_fraction * 180.0) + (1.0 - abs(mixture - 0.85) * 2.5) * 80.0
        if "FAULT_SENSOR_DRIFT" in faults:
            target_egt += faults["FAULT_SENSOR_DRIFT"] * 65.0

        tau_egt = 1.2
        self.egt_c += (target_egt - self.egt_c) * (1.0 - math.exp(-dt_s / tau_egt))

        # CHT: balance between heat generated by combustion and cooling airflow
        cooling_factor = max(0.2, (airspeed_kts / 120.0) * sigma)
        heat_input = power_bhp * 0.95
        heat_dissipated = cooling_factor * 180.0
        target_cht = ambient_temp_c + (heat_input / max(1.0, heat_dissipated)) * 60.0

        if "FAULT_CHT_DETONATION" in faults:
            target_cht += faults["FAULT_CHT_DETONATION"] * 120.0  # Spikes dangerously

        tau_cht = 7.5
        self.cht_c += (target_cht - self.cht_c) * (1.0 - math.exp(-dt_s / tau_cht))

        # 6. Lubrication: Oil Temp & Pressure
        # Engine speed drives positive displacement pump; high temp reduces oil viscosity
        viscosity_factor = max(0.5, 1.0 - (self.oil_temp_c - 75.0) * 0.006)
        target_oil_press = (20.0 + (self.rpm / max_rpm) * 55.0) * viscosity_factor
        if "FAULT_OIL_LOSS" in faults:
            target_oil_press *= max(0.05, 1.0 - faults["FAULT_OIL_LOSS"] * 0.85)

        tau_oil_p = 0.4
        self.oil_press_psi += (target_oil_press - self.oil_press_psi) * (1.0 - math.exp(-dt_s / tau_oil_p))

        target_oil_temp = ambient_temp_c + 50.0 + (power_fraction * 35.0)
        if "FAULT_OIL_LOSS" in faults:
            target_oil_temp += faults["FAULT_OIL_LOSS"] * 45.0
        tau_oil_t = 12.0
        self.oil_temp_c += (target_oil_temp - self.oil_temp_c) * (1.0 - math.exp(-dt_s / tau_oil_t))

        # Fuel pressure
        self.fuel_press_psi = 24.0 + 4.0 * (self.rpm / max_rpm)

        return {
            "rpm": round(self.rpm, 1),
            "map_inhg": round(self.map_inhg, 2),
            "cht_c": round(self.cht_c, 1),
            "egt_c": round(self.egt_c, 1),
            "power_bhp": round(power_bhp, 1),
            "fuel_flow_gph": round(fuel_flow_gph, 2),
            "fuel_press_psi": round(self.fuel_press_psi, 1),
            "oil_press_psi": round(self.oil_press_psi, 1),
            "oil_temp_c": round(self.oil_temp_c, 1),
            "vibration_ips": round(0.12 + 0.15 * (self.rpm / max_rpm), 2),
        }
